"""
AiPet — an on-chain AI tamagotchi on GenLayer (GenVM, Python).

The pet lives inside the contract: its state (satiety / mood / health / age) is
stored on-chain, drifts with idle time and with REAL weather (read from the web
via gl.nondet.web), and its lines are generated by an LLM right inside the
contract.

Non-deterministic work (web + LLM) runs ONLY inside gl.eq_principle.* /
gl.vm.run_nondet_unsafe blocks. Storage is NOT accessible inside those blocks —
all needed values are gathered in ordinary (deterministic) code and passed into
the block via a closure; the block's result is written to storage afterwards.
"""

