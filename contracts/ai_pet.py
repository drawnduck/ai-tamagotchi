class AiPet(gl.Contract):
    owner: Address
    name: str
    persona: str
    city: str
    satiety: u256
    mood: u256
    health: u256
    last_interaction_ts: u256
    birth_ts: u256
    total_fed: u256           # total fed (wei) — grows on feed()
    allow_public_feed: bool    # may non-owners feed it? (community pet)
    last_quote: str
    history: DynArray[str]
    alive: bool                # health hitting 0 kills it until revive()
    died_ts: u256              # when it died (0 while alive)
    revives: u256              # how many times it came back
    time_scale: u256           # virtual seconds per real second — see _elapsed()
    last_market: str           # last market category seen by check(), for display
    feeders: TreeMap[Address, u256]   # who fed how much (wei) — community leaderboard
    # --- social life (see visit / receive_visit) ---
    friends: TreeMap[Address, u256]   # other pets -> how many times we have met
    last_met: TreeMap[Address, u256]  # other pets -> real ts of the last COUNTED meeting
    visits_sent: u256
    visits_received: u256
    pending_from: Address      # a guest we have not answered yet (zero = none)
    pending_name: str          # their name, read from THEIR contract, sanitized
    pending_quote: str         # their line — foreign text, sanitized, never our voice
    # --- character drift (see TRAITS) ---
    trait_levels: DynArray[u256]   # one slot per TRAITS entry, 0..TRAIT_MAX
    last_evolved_ts: u256          # real ts of the last nudge (0 = never)
    evolutions: u256               # how many times the character has moved
    evolving: bool                 # owner's switch: may experience change it?
    # --- health regen (see _decay) ---
    health_regen_acc: u256         # well-fed billed hours banked toward +1 health

    # ---- constructor (private, no decorator) ----
    def __init__(self, name: str, persona: str, city: str, time_scale: int = 1,
                 owner: str = ""):
        """`time_scale` is how many virtual seconds pass per real second.

        1 is real time and the default. Anything higher makes a demo pet: at
        3600 one real second is a virtual hour, so it ages a day every 24 s and
        starves to death in about two and a half minutes instead of 150 hours.
        Nothing else in the contract changes — the rates stay per virtual hour.

        Set once and never mutable: `last_interaction_ts` stores real seconds and
        is scaled on read, so changing this mid-life would rewrite the past.

        `owner` deploys the pet on someone else's behalf. `gl.message.sender`
        inside a constructor is whoever sent the deploy, so without this argument
        a pet can only ever belong to whoever paid for the deployment — no
        gifting one, and no deploying for a user from a script or another
        contract. Blank keeps the sender. Anyone may set it to any address, which
        is not a hole: the worst you can do is give someone a pet.
        """
        scale = int(time_scale)
        if scale < 1:
            raise gl.vm.UserError("time_scale must be at least 1")
        self.time_scale = u256(scale)
        self.last_market = ""
        self.owner = Address(owner) if owner else gl.message.sender_address
        self.name = name
        self.persona = persona
        self.city = city
        self.satiety = u256(HATCH_SATIETY)
        self.mood = u256(HATCH_MOOD)
        self.health = u256(HATCH_HEALTH)
        self.health_regen_acc = u256(0)
        now = _now()
        self.birth_ts = u256(now)
        self.last_interaction_ts = u256(now)
        self.total_fed = u256(0)
        self.allow_public_feed = True
        self.last_quote = ""
        self.alive = True
        self.died_ts = u256(0)
        self.revives = u256(0)
        self.visits_sent = u256(0)
        self.visits_received = u256(0)
        self.pending_from = Address(bytes(20))
        self.pending_name = ""
        self.pending_quote = ""
        # one counter per trait, in TRAITS order — that order IS the schema
        for _ in TRAITS:
            self.trait_levels.append(u256(0))
        self.last_evolved_ts = u256(0)
        self.evolutions = u256(0)
        self.evolving = True

    # ===================== internal mechanics (deterministic) ================

    def _elapsed(self, since_ts: int) -> int:
        """Virtual seconds since a stored (real) timestamp. See __init__."""
        now = _now()
        if since_ts == 0 or now <= since_ts:
            return 0
        return (now - since_ts) * int(self.time_scale)

    def _decay(self) -> int:
        """Apply state drift for idle time. Returns idle_hours.

        Neglect is fatal: while starving, health bleeds off and reaching 0 kills
        the pet — every action is then blocked until someone pays for revive().

        `last_interaction_ts` is a DECAY CURSOR, not "when the owner last showed
        up", and this method is the only thing that moves it while the pet is
        alive. Drift is billed in whole virtual hours, so the cursor advances by
        exactly the hours just billed and the leftover minutes carry over to the
        next action.

        Stamping it to `_now()` at the end of an action instead — which is what
        this contract used to do — threw that remainder away every single time.
        The result was not a rounding error but a free pet: acting every 59
        virtual minutes kept idle_h at 0 forever, so a pet could be petted to a
        permanent mood of 100 and never lose a point of satiety, never age into
        starvation, and never need anyone to buy it food. Measured: 12 free
        pet() calls across 11.8 virtual hours left satiety at its initial 70.

        THE HOURS ARE BILLED ONE AT A TIME, and that is not a refactor of the
        old lump arithmetic — it is a different answer. The lump form subtracted
        every idle hour of hunger in one go, looked at the satiety that was LEFT,
        and if it was under STARVE_SATIETY charged health for ALL of the idle
        hours. Thirty idle hours from a fresh hatch therefore cost 30 health,
        when only the last four of them were actually hungry. Walking the hours
        charges each one at the state it really had: same thirty hours, 4 health.

        Satiety is read at the START of each hour, before that hour's hunger. A
        pet that begins an hour at exactly STARVE_SATIETY ate recently enough not
        to be starving through it; billing hunger first would make every
        threshold arrive a whole hour early.

        A pet that is already at health 0 when this runs — which only
        _apply_world's freezing chip can do — dies here on the next write, with
        no further hunger billed. That is deliberate: health 0 has always meant
        dead, and the old code simply had no path that noticed.
        """
        cursor = int(self.last_interaction_ts)
        elapsed = self._elapsed(cursor)
        idle_h = elapsed // 3600
        if idle_h == 0:
            return 0
        # Consume what was billed and keep the rest. Back off from now by the
        # unbilled remainder rather than adding to the cursor, so the arithmetic
        # stays exact at time_scale 1 (where the remainder is already real
        # seconds) instead of dividing 3600 by the scale and losing the odd one.
        leftover = elapsed - idle_h * 3600
        stamp = u256(_now() - leftover // int(self.time_scale))

        if idle_h > DECAY_BILL_CAP:
            # A year of neglect. Playing it out hour by hour is a loop nobody can
            # pay for, and the answer at the end is the same one anyway: the cap
            # sits far above the longest span a pet can survive untended, so
            # every path through here ends in a corpse. The alternative — give up
            # and bill nothing — would leave an abandoned pet alive and perfect
            # forever, which is the one outcome the whole mechanic exists to
            # prevent.
            self.satiety = u256(0)
            self.mood = u256(0)
            self.health = u256(0)
            self.health_regen_acc = u256(0)
            self.last_interaction_ts = stamp
            self._die()
            return idle_h

        # Storage is read ONCE here and written ONCE below. Up to DECAY_BILL_CAP
        # iterations times six storage operations each is the difference between
        # a cheap action and one that runs out of gas; inside the loop these are
        # plain ints, and nothing reads or writes a field.
        sat = int(self.satiety)
        mood = int(self.mood)
        health = int(self.health)
        acc = int(self.health_regen_acc)

        for _ in range(idle_h):
            if health == 0:
                break
            if sat < STARVE_SATIETY:
                health -= STARVE_HEALTH_PER_HOUR
                if health < 0:
                    health = 0
                acc = 0
            elif sat >= HEALTH_REGEN_SATIETY:
                acc += 1
                if acc >= HEALTH_REGEN_HOURS:
                    acc = 0
                    if health < HATCH_HEALTH:
                        health += 1
            else:
                # The middle band, STARVE_SATIETY..HEALTH_REGEN_SATIETY-1: no
                # bleed, and no banking either. A remainder carried through a
                # slump would let three well-fed hours, a crash to 50 and a
                # single refill produce a point of health out of nowhere.
                acc = 0
            sat -= SATIETY_PER_HOUR
            if sat < 0:
                sat = 0
            mood -= MOOD_PER_HOUR
            if mood < 0:
                mood = 0

        self.satiety = u256(sat)
        self.mood = u256(mood)
        self.health = u256(health)
        self.health_regen_acc = u256(acc)
        self.last_interaction_ts = stamp
        # _die() writes mood and a history line, so the flush above has to happen
        # FIRST — flushing afterwards would overwrite the death it just announced.
        if health == 0:
            self._die()
        return idle_h

    def _die(self) -> None:
        """Mark the pet dead and leave a final line in the feed (deterministic)."""
        if not self.alive:
            return
        self.alive = False
        self.died_ts = u256(_now())
        self.mood = u256(0)
        self._record(
            f"{str(self.name)} went quiet from neglect. Only a revive can bring it back."
        )
        PetDied(
            age_days=self._age_days(),
            stage=_stage(self._age_days()),
            revives=int(self.revives),
            revive_cost_wei=str(REVIVE_COST),
        ).emit()

    def _require_alive(self) -> None:
        if not self.alive:
            raise gl.vm.UserError("pet is dead — call revive() to bring it back")

    def _tick(self) -> tuple:
        """Shared preamble for every action: reject if dead, then apply drift.

        Returns (idle_hours, still_alive). A False means the drift just killed
        the pet, so the caller must bail out before spending an LLM call.
        """
        self._require_alive()
        idle_h = self._decay()
        return idle_h, bool(self.alive)

    def _nourish(self, who: Address, value: int) -> int:
        """Book incoming value as food. Returns the satiety gained.

        Shared by feed() and __receive__ so the two can never disagree about the
        exchange rate, the cap or the leaderboard — the only difference between
        them should be that feed() also gets a line out of it.
        """
        self.total_fed = u256(int(self.total_fed) + value)
        self._credit_feeder(who, value)
        gain = value // WEI_PER_SATIETY
        if gain > FEED_CAP:
            gain = FEED_CAP
        self.satiety = _clamp(int(self.satiety) + gain)
        self.mood = _clamp(int(self.mood) + FEED_MOOD)
        # A real meal mends a point of the scar, but only if it actually lands
        # the pet in the well-fed band: 0.10 GEN into a starving pet (gain 10,
        # satiety 5 -> 15) is a snack, not care. Deliberately +HEALTH_FEED_HEAL
        # and not +gain — a FEED_CAP meal heals exactly as much as a modest one,
        # so health cannot be bought back in one transaction.
        if gain >= HEALTH_FEED_GAIN_MIN and int(self.satiety) >= HEALTH_REGEN_SATIETY:
            self.health = _clamp(int(self.health) + HEALTH_FEED_HEAL)
        return gain

    def _credit_feeder(self, who: Address, amount: int) -> None:
        """Track per-address contributions for the community leaderboard.

        The single funnel for incoming value — feed() and a paid revive() both
        land here, so PetFed covers both without either having to remember to.
        """
        if amount <= 0:
            return
        prev = self.feeders.get(who)
        total = (int(prev) if prev is not None else 0) + amount
        self.feeders[who] = u256(total)
        PetFed(
            who,
            amount_wei=str(amount),
            feeder_total_wei=str(total),
            pet_total_wei=str(int(self.total_fed)),
        ).emit()

    def _age_days(self) -> int:
        return self._elapsed(int(self.birth_ts)) // 86400

    def _age_days_at_billed_hour(self, idle_h: int, billed: int, leftover: int) -> int:
        """Age in days at the START of billed hour `billed` (0-indexed).

        Every rate in this contract is about to become a function of life stage,
        and a pet that ages in the middle of a long bill has to be charged at the
        rate it HAD during each hour, not the one it happens to have now. That
        means walking backwards from the present: at the start of hour `billed`
        there were still (idle_h - billed) whole hours to come, plus `leftover`.

        Subtracting `leftover` is the part that is easy to forget and impossible
        to notice. Those are seconds that have already passed but have NOT been
        billed — they sit between the last billed hour and now. Leave them in and
        every hour's age is overstated by up to an hour, which at a stage
        boundary is not a rounding error but the wrong rate table.
        """
        ahead = (idle_h - billed) * 3600 + leftover
        age = self._elapsed(int(self.birth_ts)) - ahead
        return age // 86400 if age > 0 else 0

    def _snapshot(self, idle_hours: int) -> dict:
        """Flat state snapshot for prompt building (ordinary code, not non-det)."""
        return {
            "name": str(self.name),
            "persona": str(self.persona),
            "satiety": int(self.satiety),
            "mood": int(self.mood),
            "health": int(self.health),
            "age_days": self._age_days(),
            "stage": _stage(self._age_days()),
            "idle_hours": idle_hours,
            "character": self._character(),
        }

    def _note(self, line: str) -> None:
        """Append a line to the feed WITHOUT claiming the pet said it.

        `last_quote` is what the UI prints in the speech bubble, so a guest's
        words must never land there — they are another contract's text.
        """
        self.history.append(line)
        while len(self.history) > HISTORY_MAX:
            self.history.pop(0)

    def _record(self, quote: str) -> None:
        """The pet's own voice: shown in the bubble and kept in the feed."""
        self.last_quote = quote
        self._note(quote)

    # ---- social bookkeeping ----

    def _count_meeting(self, other: Address) -> bool:
        """Bump the friendship counter. True if this meeting pays out mood.

        Every meeting counts towards the friendship; only the first one inside
        VISIT_COOLDOWN_H moves the mood, and the cooldown runs from the last
        meeting that paid — otherwise a spammer's failed attempts would keep
        pushing the window forward and never let a real friend through.
        """
        seen = self.last_met.get(other)
        last_ts = int(seen) if seen is not None else 0
        fresh = last_ts == 0 or self._elapsed(last_ts) // 3600 >= VISIT_COOLDOWN_H
        met = self.friends.get(other)
        self.friends[other] = u256((int(met) if met is not None else 0) + 1)
        if fresh:
            self.last_met[other] = u256(_now())
        return fresh

    def _greeting(self) -> tuple:
        """The unanswered guest as (fenced data line, name to answer).

        Both empty when nobody is waiting. The two halves go to different places
        in the prompt for different reasons — see _build_prompt.
        """
        name = str(self.pending_name)
        if not name:
            return "", ""
        quote = str(self.pending_quote)
        if not quote:
            return f"another pet, {name}, came by to see you;", name
        return f'another pet, {name}, came by and said: "{quote}";', name

    # ---- character drift ----

    def _levels(self) -> list:
        """Trait counters as a plain list, padded if TRAITS grew since deployment.

        A contract deployed before a trait was added has a shorter array and no
        way to grow it — storage is fixed at construction. Padding here keeps such
        a pet readable instead of throwing on every action.
        """
        stored = [int(v) for v in self.trait_levels]
        while len(stored) < len(TRAITS):
            stored.append(0)
        return stored[: len(TRAITS)]

    def _character(self) -> str:
        return _character_phrase(self._levels())

    def _evolve(self, trait) -> str:
        """Let one experience move the character. Returns the trait moved, or "".

        Everything that can say no says no here, in deterministic code:

        * the owner may have switched drift off;
        * the word must be one of TRAITS — an invented one is ignored, never
          stored, and certainly never rendered into a prompt;
        * a trait stops at TRAIT_MAX, so a pet cannot become infinitely gloomy;
        * and only one nudge per EVOLVE_COOLDOWN_H virtual hours, so a character
          is something a pet grows into rather than something an owner can buy in
          an afternoon of clicking.
        """
        if not self.evolving:
            return ""
        if not isinstance(trait, str) or trait not in TRAITS:
            return ""
        last = int(self.last_evolved_ts)
        if last != 0 and self._elapsed(last) // 3600 < EVOLVE_COOLDOWN_H:
            return ""

        index = TRAITS.index(trait)
        levels = self._levels()
        if levels[index] >= TRAIT_MAX:
            return ""
        if index >= len(self.trait_levels):
            return ""                      # storage predates this trait
        self.trait_levels[index] = u256(levels[index] + 1)
        self.last_evolved_ts = u256(_now())
        self.evolutions = u256(int(self.evolutions) + 1)
        PetEvolved(
            trait,
            level=levels[index] + 1,
            character=self._character(),
            evolutions=int(self.evolutions),
        ).emit()
        return trait

    def _only_owner(self) -> None:
        if gl.message.sender_address != self.owner:
            raise gl.vm.UserError("only owner can do this")

    # ---- non-det: LLM line via leader + validator ----
    def _speak(self, prompt: str) -> dict:
        """Generate a line. No storage access inside the block — only `prompt`.

        WHY `run_nondet_unsafe` AND NOT AN `eq_principle`. This is the one
        non-deterministic call in the contract whose output is *meant* to differ
        between validators: two models writing a sentence in character will never
        agree on it, so `strict_eq` would fail every round, and
        `prompt_comparative` would be asking an LLM whether two cat noises mean
        the same thing — a judgement with no stable answer, paid for on every
        action.

        So the shape is the contract, and the text is flavour. The validator
        accepts any structurally valid reply and the deterministic code that
        follows takes only bounded values out of it: `mood_delta` is clamped to
        ±3 (`_apply_reply`), `trait` must be a member of TRAITS (`_evolve`), and
        `quote` is truncated and only ever displayed. A leader that returns
        nonsense costs a rotation, never a corrupt state.
        """
        def leader():
            return gl.nondet.exec_prompt(prompt, response_format="json")

        def validator(res) -> bool:
            if not isinstance(res, gl.vm.Return):
                return False
            return _valid_reply(res.calldata)

        out = gl.vm.run_nondet_unsafe(leader, validator)
        # in case the runtime hands back a Return wrapper instead of the payload
        if isinstance(out, gl.vm.Return):
            out = out.calldata
        return out

    def _finish(self, action: str, reply: dict, answered_guest: bool = True) -> str:
        """Close out an action: apply the reply, clear the guest, announce it.

        Every write method ends here, which is what keeps the event and the state
        it reports from drifting apart.

        `answered_guest=False` is for the one action that speaks without speaking
        to whoever is waiting at home — see visit().
        """
        quote = self._apply_reply(reply)
        # The same reply that produced the line may also have moved the character.
        # _evolve decides whether it is allowed to — see there for every way it
        # can say no.
        moved = self._evolve(reply.get("trait", ""))
        # NB: the decay clock is deliberately NOT stamped here. It is a cursor
        # over billed time, owned by _decay() alone — see there.
        # Whatever the pet just said, it said it knowing a guest had been by —
        # every action feeds _greeting() into the prompt. The greeting has
        # now been answered, so it must not colour the next line as well.
        if answered_guest:
            self._clear_greeting()
        PetSpoke(
            action,
            gl.message.sender_address,
            quote=quote,
            satiety=int(self.satiety),
            mood=int(self.mood),
            health=int(self.health),
            stage=_stage(self._age_days()),
            age_days=self._age_days(),
            character=self._character(),
            grew=moved,
        ).emit()
        return quote

    def _clear_greeting(self) -> None:
        self.pending_from = Address(bytes(20))
        self.pending_name = ""
        self.pending_quote = ""

    def _apply_reply(self, reply: dict) -> str:
        """Apply the LLM result to mood and record the line (deterministic)."""
        delta = int(reply["mood_delta"])
        if delta < -3:
            delta = -3
        elif delta > 3:
            delta = 3
        self.mood = _clamp(int(self.mood) + delta)
        quote = str(reply["quote"])[:280]
        self._record(quote)
        return quote

    def _apply_world(self, world: dict) -> None:
        """Real weather's effect on wellbeing (deterministic)."""
        cond = world.get("condition", "")
        if cond in ("rain", "snow", "thunderstorm", "drizzle"):
            self.mood = _clamp(int(self.mood) - 3)
        elif cond == "clear":
            self.mood = _clamp(int(self.mood) + 3)
        if world.get("temp") == "freezing":
            self.health = _clamp(int(self.health) - 1)
        # the crypto market is this pet's other weather
        market = str(world.get("market", "unknown"))
        self.mood = _clamp(int(self.mood) + MARKET_MOOD.get(market, 0))
        self.last_market = market

    # ===================== write methods ====================================

    @gl.public.write
    def check(self) -> str:
        """Main method: reads the real world (web), recomputes drift, speaks a line."""
        idle_h, still_alive = self._tick()
        if not still_alive:
            return str(self.last_quote)

        # --- non-det #1: read the weather (coarsened fields -> stable consensus) ---
        city = str(self.city)
        # Yesterday and the day before — never today: a past date is settled, so
        # the endpoint returns the same number to everyone. See _read_market.
        day, prev_day = _utc_day(-1), _utc_day(-2)

        def read():
            return _read_world(city, day, prev_day)

        world = json.loads(gl.eq_principle.strict_eq(read))

        # deterministically apply the weather
        self._apply_world(world)

        # --- non-det #2: a line in character ---
        snap = self._snapshot(idle_h)
        foreign, guest = self._greeting()
        prompt = _build_prompt(
            snap, world, "you look around and check the world", foreign, guest
        )
        reply = self._speak(prompt)

        return self._finish("check", reply)

    @gl.public.write.payable
    def feed(self) -> str:
        """Feed the pet (payable). Satiety grows proportionally to the GEN sent."""
        if not self.allow_public_feed and gl.message.sender_address != self.owner:
            raise gl.vm.UserError("feeding is owner-only for this pet")

        idle_h, still_alive = self._tick()
        if not still_alive:
            # The drift this very call applied is what killed it. The free actions
            # return the death line here and let the client show it; this one is
            # payable, and returning would keep the sender's GEN while crediting
            # nobody — not the leaderboard, not total_fed, not the pet, which is
            # dead. Raising reverts, so the money goes home. That is exactly what
            # __receive__ does in the identical situation, which is what _nourish
            # promises: those two paths never disagree about incoming value.
            raise gl.vm.UserError("pet just starved — call revive() to bring it back")

        gain = self._nourish(gl.message.sender_address, int(gl.message.value))

        snap = self._snapshot(idle_h)
        situation = (
            "you were just fed a tasty meal" if gain > 0
            else "you got petted but no food was given"
        )
        foreign, guest = self._greeting()
        prompt = _build_prompt(snap, None, situation, foreign, guest)
        reply = self._speak(prompt)

        return self._finish("feed", reply)

    @gl.public.write
    def play(self) -> str:
        """Play: mood goes up, satiety goes down."""
        idle_h, still_alive = self._tick()
        if not still_alive:
            return str(self.last_quote)
        self.mood = _clamp(int(self.mood) + 10)
        self.satiety = _clamp(int(self.satiety) - 8)

        snap = self._snapshot(idle_h)
        foreign, guest = self._greeting()
        prompt = _build_prompt(
            snap, None, "you just had a fun play session", foreign, guest
        )
        reply = self._speak(prompt)

        return self._finish("play", reply)

