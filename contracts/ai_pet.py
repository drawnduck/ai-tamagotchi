    @gl.public.write
    def reset_character(self) -> None:
        """Forget everything experience has added. The persona itself is untouched.

        The escape hatch for the owner: drift is the pet's, but the pet is the
        owner's. Also resets the cooldown, so a fresh character can start forming
        immediately rather than after the next four virtual hours.
        """
        self._only_owner()
        for i in range(len(self.trait_levels)):
            self.trait_levels[i] = u256(0)
        self.last_evolved_ts = u256(0)

