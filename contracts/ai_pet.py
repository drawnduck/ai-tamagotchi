    @gl.public.view
    def get_friends(self, limit: int) -> list:
        """Who this pet has met, most-met first. `limit <= 0` returns everyone."""
        rows = []
        for addr, met in self.friends.items():
            seen = self.last_met.get(addr)
            rows.append({
                "address": addr.as_hex,
                "meetings": int(met),
                "last_met_ts": int(seen) if seen is not None else 0,
            })
        rows.sort(key=lambda r: r["meetings"], reverse=True)
        n = int(limit)
        return rows if n <= 0 else rows[:n]

