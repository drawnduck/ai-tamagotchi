class AiPet(gl.Contract):
    owner: Address
    name: str
    persona: str
    city: str
    satiety: u256
    mood: u256
    health: u256
    last_interaction_ts: u256
    birth_ts: u256
    total_fed: u256           # total fed (wei) — grows on feed()
    # --- the till (see _effective_balance / _withdrawable / _till_revive_ready) ---
    burned_wei: u256          # what the till has spent reviving this pet — locked, never sent
    till_revive_at_fed: u256  # total_fed at the last till-revive (0 = never happened)
    allow_public_feed: bool    # may non-owners feed it? (community pet)
    last_quote: str
    history: DynArray[str]
    alive: bool                # health hitting 0 kills it until revive()
    died_ts: u256              # when it died (0 while alive)
    revives: u256              # how many times it came back
    time_scale: u256           # virtual seconds per real second — see _elapsed()
    last_market: str           # last market category seen by check(), for display
    feeders: TreeMap[Address, u256]   # who fed how much (wei) — community leaderboard
    # --- social life (see visit / receive_visit) ---
    friends: TreeMap[Address, u256]   # other pets -> how many times we have met
    last_met: TreeMap[Address, u256]  # other pets -> real ts of the last COUNTED meeting
    visits_sent: u256
    visits_received: u256
    # Three parallel arrays, not one array of a struct: GenVM storage has no
    # record type, and index i of each is one guest. They are only ever appended
    # to and popped from together, and _queue_ok() checks that before any
    # mutation — a desynced queue would hand one guest's words to another
    # guest's name, which is the one attack _sanitize cannot defend against.
    pending_from: DynArray[Address]   # guests we have not answered yet, oldest first
    pending_name: DynArray[str]       # their names, read from THEIR contracts, sanitized
    pending_quote: DynArray[str]      # their lines — foreign text, sanitized, never our voice
    # --- character drift (see TRAITS) ---
    trait_levels: DynArray[u256]   # one slot per TRAITS entry, 0..TRAIT_MAX
    last_evolved_ts: u256          # real ts of the last nudge (0 = never)
    evolutions: u256               # how many times the character has moved
    evolving: bool                 # owner's switch: may experience change it?
    # --- health regen (see _decay) ---
    health_regen_acc: u256         # well-fed billed hours banked toward +1 health
    # --- the world outside (see _apply_world / _mood_drain_per_hour) ---
    last_condition: str            # last coarsened weather category check() saw
    last_temp: str                 # last coarsened temperature band — display only
    last_world_ts: u256            # real ts of that reading (0 = never looked out)

    # ---- constructor (private, no decorator) ----
    def __init__(self, name: str, persona: str, city: str, time_scale: int = 1,
                 owner: str = ""):
        """`time_scale` is how many virtual seconds pass per real second.

        1 is real time and the default. Anything higher makes a demo pet: at
        3600 one real second is a virtual hour, so it ages a day every 24 s and
        starves to death in about two and a half minutes instead of 150 hours.
        Nothing else in the contract changes — the rates stay per virtual hour.

        Set once and never mutable: `last_interaction_ts` stores real seconds and
        is scaled on read, so changing this mid-life would rewrite the past.

        `owner` deploys the pet on someone else's behalf. `gl.message.sender`
        inside a constructor is whoever sent the deploy, so without this argument
        a pet can only ever belong to whoever paid for the deployment — no
        gifting one, and no deploying for a user from a script or another
        contract. Blank keeps the sender. Anyone may set it to any address, which
        is not a hole: the worst you can do is give someone a pet.
        """
        scale = int(time_scale)
        if scale < 1:
            raise gl.vm.UserError("time_scale must be at least 1")
        self.time_scale = u256(scale)
        self.last_market = ""
        # No world has been read yet, and the timestamp is what says so: an empty
        # condition would be indistinguishable from a check() that came back
        # blank, and _world_is_fresh has to be able to tell those apart.
        self.last_condition = ""
        self.last_temp = ""
        self.last_world_ts = u256(0)
        self.owner = Address(owner) if owner else gl.message.sender_address
        self.name = name
        self.persona = persona
        self.city = city
        self.satiety = u256(HATCH_SATIETY)
        self.mood = u256(HATCH_MOOD)
        self.health = u256(HATCH_HEALTH)
        self.health_regen_acc = u256(0)
        now = _now()
        self.birth_ts = u256(now)
        self.last_interaction_ts = u256(now)
        self.total_fed = u256(0)
        self.burned_wei = u256(0)
        self.till_revive_at_fed = u256(0)
        self.allow_public_feed = True
        self.last_quote = ""
        self.alive = True
        self.died_ts = u256(0)
        self.revives = u256(0)
        self.visits_sent = u256(0)
        self.visits_received = u256(0)
        # the three greeting queues start empty; a DynArray needs no initialiser
        # one counter per trait, in TRAITS order — that order IS the schema
        for _ in TRAITS:
            self.trait_levels.append(u256(0))
        self.last_evolved_ts = u256(0)
        self.evolutions = u256(0)
        self.evolving = True

    # ===================== internal mechanics (deterministic) ================

    def _elapsed(self, since_ts: int) -> int:
        """Virtual seconds since a stored (real) timestamp. See __init__."""
        now = _now()
        if since_ts == 0 or now <= since_ts:
            return 0
        return (now - since_ts) * int(self.time_scale)

    def _decay(self) -> int:
        """Apply state drift for idle time. Returns idle_hours.

        Neglect is fatal: while starving, health bleeds off and reaching 0 kills
        the pet — every action is then blocked until someone pays for revive().

        `last_interaction_ts` is a DECAY CURSOR, not "when the owner last showed
        up", and this method is the only thing that moves it while the pet is
        alive. Drift is billed in whole virtual hours, so the cursor advances by
        exactly the hours just billed and the leftover minutes carry over to the
        next action.

        Stamping it to `_now()` at the end of an action instead — which is what
        this contract used to do — threw that remainder away every single time.
        The result was not a rounding error but a free pet: acting every 59
        virtual minutes kept idle_h at 0 forever, so a pet could be petted to a
        permanent mood of 100 and never lose a point of satiety, never age into
        starvation, and never need anyone to buy it food. Measured: 12 free
        pet() calls across 11.8 virtual hours left satiety at its initial 70.

        THE HOURS ARE BILLED ONE AT A TIME, and that is not a refactor of the
        old lump arithmetic — it is a different answer. The lump form subtracted
        every idle hour of hunger in one go, looked at the satiety that was LEFT,
        and if it was under STARVE_SATIETY charged health for ALL of the idle
        hours. Thirty idle hours from a fresh hatch therefore cost 30 health,
        when only the last four of them were actually hungry. Walking the hours
        charges each one at the state it really had: same thirty hours, 4 health.

        Satiety is read at the START of each hour, before that hour's hunger. A
        pet that begins an hour at exactly STARVE_SATIETY ate recently enough not
        to be starving through it; billing hunger first would make every
        threshold arrive a whole hour early.

        A pet that is already at health 0 when this runs — which only
        _apply_world's freezing chip can do — dies here on the next write, with
        no further hunger billed. That is deliberate: health 0 has always meant
        dead, and the old code simply had no path that noticed.

        Each hour is also billed at the rates of the life stage the pet was in
        DURING that hour (STAGE_SATIETY_PER_HOUR / STAGE_STARVE_PER_HOUR), which
        is why the loop carries an age and not just a counter. An owner who
        leaves for a week comes back to a bill that was egg-priced while the pet
        was an egg and kitten-priced once it was a kitten; settling the whole
        absence at today's rate would make the pet's own birthday a thing worth
        timing your neglect around.

        The same is true of the weather. Each hour's MOOD drain is billed under
        the last world check() read, for as long as that reading is fresh — see
        _mood_drain_per_hour. THERE IS STILL NO WEB CALL HERE: what the loop
        reads is a category already agreed on by consensus and written to
        storage, which is the only way a persistent world is affordable at all.
        An hour that started before that reading was taken is billed at the base
        rate, so the very check() that writes the world never charges its own
        idle hours for it — the hangover starts with the next write.
        """
        cursor = int(self.last_interaction_ts)
        elapsed = self._elapsed(cursor)
        idle_h = elapsed // 3600
        if idle_h == 0:
            return 0
        # Consume what was billed and keep the rest. Back off from now by the
        # unbilled remainder rather than adding to the cursor, so the arithmetic
        # stays exact at time_scale 1 (where the remainder is already real
        # seconds) instead of dividing 3600 by the scale and losing the odd one.
        leftover = elapsed - idle_h * 3600
        stamp = u256(_now() - leftover // int(self.time_scale))

        if idle_h > DECAY_BILL_CAP:
            # A year of neglect. Playing it out hour by hour is a loop nobody can
            # pay for, and the answer at the end is the same one anyway: the cap
            # sits far above the longest span a pet can survive untended, so
            # every path through here ends in a corpse. The alternative — give up
            # and bill nothing — would leave an abandoned pet alive and perfect
            # forever, which is the one outcome the whole mechanic exists to
            # prevent.
            self.satiety = u256(0)
            self.mood = u256(0)
            self.health = u256(0)
            self.health_regen_acc = u256(0)
            self.last_interaction_ts = stamp
            self._die()
            return idle_h

        # Storage is read ONCE here and written ONCE below. Up to DECAY_BILL_CAP
        # iterations times six storage operations each is the difference between
        # a cheap action and one that runs out of gas; inside the loop these are
        # plain ints, and nothing reads or writes a field.
        sat = int(self.satiety)
        mood = int(self.mood)
        health = int(self.health)
        acc = int(self.health_regen_acc)
        age_secs = self._elapsed(int(self.birth_ts))
        # The world, hoisted for the same reason: the hangover needs three fields
        # and an elapsed time on every one of up to DECAY_BILL_CAP iterations,
        # and reading them per hour is the gas profile this loop exists to avoid.
        # -1 for "no world has ever been read" — see _world_is_fresh.
        world_ts = int(self.last_world_ts)
        world_age = self._elapsed(world_ts) if world_ts else -1
        cond = str(self.last_condition)
        market = str(self.last_market)

        for billed in range(idle_h):
            if health == 0:
                break
            # The rates belong to the stage the pet was in DURING this hour, not
            # the stage it is in now. A pet that hatches or grows up mid-bill is
            # charged egg rates for the egg hours and hatchling rates for the
            # rest — anything else would let a long absence be settled entirely
            # at whichever rate happened to be cheapest at the far end.
            stage = _stage(_age_days_at_billed_hour(age_secs, idle_h, billed, leftover))
            if sat < STARVE_SATIETY:
                health -= STAGE_STARVE_PER_HOUR[stage]
                if health < 0:
                    health = 0
                acc = 0
            elif sat >= HEALTH_REGEN_SATIETY:
                acc += 1
                if acc >= HEALTH_REGEN_HOURS:
                    acc = 0
                    if health < HATCH_HEALTH:
                        health += 1
            else:
                # The middle band, STARVE_SATIETY..HEALTH_REGEN_SATIETY-1: no
                # bleed, and no banking either. A remainder carried through a
                # slump would let three well-fed hours, a crash to 50 and a
                # single refill produce a point of health out of nowhere.
                acc = 0
            sat -= STAGE_SATIETY_PER_HOUR[stage]
            if sat < 0:
                sat = 0
            # Mood is billed under the weather this hour was actually lived in.
            # No web call happens here or anywhere near here — this is the last
            # category check() agreed on, being spent slowly.
            mood -= _mood_drain_per_hour(
                _world_is_fresh(world_age, idle_h, billed, leftover), cond, market
            )
            if mood < 0:
                mood = 0

        self.satiety = u256(sat)
        self.mood = u256(mood)
        self.health = u256(health)
        self.health_regen_acc = u256(acc)
        self.last_interaction_ts = stamp
        # _die() writes mood and a history line, so the flush above has to happen
        # FIRST — flushing afterwards would overwrite the death it just announced.
        if health == 0:
            self._die()
        return idle_h

    def _die(self) -> None:
        """Mark the pet dead and leave a final line in the feed (deterministic)."""
        if not self.alive:
            return
        self.alive = False
        self.died_ts = u256(_now())
        self.mood = u256(0)
        self._record(
            f"{str(self.name)} went quiet from neglect. Only a revive can bring it back."
        )
        PetDied(
            age_days=self._age_days(),
            stage=_stage(self._age_days()),
            revives=int(self.revives),
            revive_cost_wei=str(REVIVE_COST),
        ).emit()

    def _require_alive(self) -> None:
        if not self.alive:
            raise gl.vm.UserError("pet is dead — call revive() to bring it back")

    def _tick(self) -> tuple:
        """Shared preamble for every action: reject if dead, then apply drift.

        Returns (idle_hours, still_alive). A False means the drift just killed
        the pet, so the caller must bail out before spending an LLM call.
        """
        self._require_alive()
        idle_h = self._decay()
        return idle_h, bool(self.alive)

    def _nourish(self, who: Address, value: int) -> int:
        """Book incoming value as food. Returns the satiety gained.

        Shared by feed() and __receive__ so the two can never disagree about the
        exchange rate, the cap or the leaderboard — the only difference between
        them should be that feed() also gets a line out of it.
        """
        self.total_fed = u256(int(self.total_fed) + value)
        self._credit_feeder(who, value)
        gain = value // WEI_PER_SATIETY
        if gain > FEED_CAP:
            gain = FEED_CAP
        self.satiety = _clamp(int(self.satiety) + gain)
        self.mood = _clamp(int(self.mood) + FEED_MOOD)
        # A real meal mends a point of the scar, but only if it actually lands
        # the pet in the well-fed band: 0.10 GEN into a starving pet (gain 10,
        # satiety 5 -> 15) is a snack, not care. Deliberately +HEALTH_FEED_HEAL
        # and not +gain — a FEED_CAP meal heals exactly as much as a modest one,
        # so health cannot be bought back in one transaction.
        if gain >= HEALTH_FEED_GAIN_MIN and int(self.satiety) >= HEALTH_REGEN_SATIETY:
            self.health = _clamp(int(self.health) + HEALTH_FEED_HEAL)
        return gain

    def _credit_feeder(self, who: Address, amount: int) -> None:
        """Track per-address contributions for the community leaderboard.

        The single funnel for incoming value — feed() and a paid revive() both
        land here, so PetFed covers both without either having to remember to.
        """
        if amount <= 0:
            return
        prev = self.feeders.get(who)
        total = (int(prev) if prev is not None else 0) + amount
        self.feeders[who] = u256(total)
        PetFed(
            who,
            amount_wei=str(amount),
            feeder_total_wei=str(total),
            pet_total_wei=str(int(self.total_fed)),
        ).emit()

    # ---- the till ----
    #
    # Food is a social contract: strangers pay to keep this pet alive, and the
    # last GEN of what they paid belongs to the next revive rather than to the
    # owner. These three read that promise off storage; nothing here writes.

    def _effective_balance(self) -> int:
        """What the till really holds: the balance minus what it has already spent.

        A till-revive does not send the GEN anywhere. It books it as burned and
        subtracts it here, for good — the wei can never be withdrawn, can never
        revive anything again, and no address ever receives it. Economically
        that is a burn; mechanically it is subtraction, which matters twice.
        An outgoing transfer only leaves `self.balance` at FINALIZATION (~30 min
        on Bradbury, and a silent no-op in direct mode), and a demo pet at
        time_scale 3600 dies again inside that window — so a balance-only guard
        would hand out the same GEN several times. Subtraction lands now.
        """
        left = int(self.balance) - int(self.burned_wei)
        return left if left > 0 else 0

    def _withdrawable(self) -> int:
        """What the owner may take out. One GEN stays behind once anyone has fed it.

        A pet nobody has ever fed made no such promise, so its dust is the
        owner's to sweep up. Same rule for public and owner-only pets: two
        branches here would be bytes spent on a surprise in the UI.

        Dust — 0 < effective < REVIVE_COST while total_fed > 0 — is INTENTIONALLY
        stuck. Too little to withdraw, too little to revive with, and it comes
        unstuck only when more food arrives. A client MUST say that out loud: a
        withdrawable of zero beside a non-zero balance reads as a broken till.
        """
        bal = self._effective_balance()
        if int(self.total_fed) > 0:
            return bal - REVIVE_COST if bal > REVIVE_COST else 0
        return bal

    def _till_revive_ready(self) -> bool:
        """Would a value==0 revive() be paid out of the till right now?

        All three guards are mandatory. Alive pets do not get revived at all.
        The GEN has to still be here to be spent. And the third one is the
        interesting one: the till must have taken in at least REVIVE_COST of NEW
        food since the last time it paid for a death. Without it a 5 GEN till
        buys five free deaths in a row and dying stops being a tax on anyone —
        on a demo pet that loop closes every ~70 seconds. A consequence worth
        stating plainly: a pet whose lifetime total_fed never reaches 1 GEN can
        never till-revive at all, however full the box looks.
        """
        if self.alive:
            return False
        if self._effective_balance() < REVIVE_COST:
            return False
        return int(self.total_fed) - int(self.till_revive_at_fed) >= REVIVE_COST

    def _age_days(self) -> int:
        return self._elapsed(int(self.birth_ts)) // 86400

    def _last_world(self):
        """The last coarsened world as prompt data, or None if none was ever read.

        NO WEB CALL. This is storage, written by the last check(), and it is what
        lets every other action put the world in its prompt: a pet that mentioned
        the rain only when someone paid for check() and then talked as if it
        lived in a featureless room was the tell that the world was decoration.

        A stale reading is still shown, flagged. Hiding it would make the pet's
        world blink out at hour 48 with nothing to say about it, while the flag
        lets the model do the obvious human thing and mention that it has not
        looked outside in days.
        """
        ts = int(self.last_world_ts)
        if ts == 0:
            return None
        return {
            "condition": str(self.last_condition),
            "temp": str(self.last_temp),
            "market": str(self.last_market),
            "stale": self._elapsed(ts) >= WORLD_STALE_H * 3600,
        }

    def _snapshot(self, idle_hours: int) -> dict:
        """Flat state snapshot for prompt building (ordinary code, not non-det)."""
        return {
            # the world every action speaks under — check() overrides it with the
            # reading it has just taken, everyone else talks about that one
            "world": self._last_world(),
            "name": str(self.name),
            "persona": str(self.persona),
            "satiety": int(self.satiety),
            "mood": int(self.mood),
            "health": int(self.health),
            "age_days": self._age_days(),
            "stage": _stage(self._age_days()),
            "idle_hours": idle_hours,
            "character": self._character(),
        }

    def _note(self, line: str) -> None:
        """Append a line to the feed WITHOUT claiming the pet said it.

        `last_quote` is what the UI prints in the speech bubble, so a guest's
        words must never land there — they are another contract's text.
        """
        self.history.append(line)
        while len(self.history) > HISTORY_MAX:
            # `del`, not `pop(0)`: GenVM's DynArray.pop() takes NO index and drops
            # the newest element, so pop(0) raises TypeError. That made the 21st
            # line of history brick every write method on the contract, revive()
            # included, permanently. `del` shifts left and shortens the array.
            del self.history[0]

    def _record(self, quote: str) -> None:
        """The pet's own voice: shown in the bubble and kept in the feed."""
        self.last_quote = quote
        self._note(quote)

    # ---- social bookkeeping ----

    def _count_meeting(self, other: Address) -> bool:
        """Bump the friendship counter. True if this meeting pays out mood.

        Every meeting counts towards the friendship; only the first one inside
        VISIT_COOLDOWN_H moves the mood, and the cooldown runs from the last
        meeting that paid — otherwise a spammer's failed attempts would keep
        pushing the window forward and never let a real friend through.
        """
        seen = self.last_met.get(other)
        last_ts = int(seen) if seen is not None else 0
        fresh = last_ts == 0 or self._elapsed(last_ts) // 3600 >= VISIT_COOLDOWN_H
        met = self.friends.get(other)
        self.friends[other] = u256((int(met) if met is not None else 0) + 1)
        if fresh:
            self.last_met[other] = u256(_now())
        return fresh

    def _queue_ok(self) -> bool:
        """True when the three greeting queues are still the same length.

        They are always mutated together, so this can only be False if a storage
        write was interrupted or a future migration went wrong. When it is False
        the queue is not partially repaired and not partially read: it simply
        stops being used, because index i of one array no longer means the same
        guest as index i of another, and pairing a stranger's words with a
        friend's name is worse than forgetting both.
        """
        n = len(self.pending_from)
        return n == len(self.pending_name) and n == len(self.pending_quote)

    def _greeting(self) -> tuple:
        """The guest at the HEAD of the queue as (fenced data line, name to answer).

        Both empty when nobody is waiting. The two halves go to different places
        in the prompt for different reasons — see _build_prompt. Only the head is
        offered: one speak answers one guest, and _clear_greeting pops that one.

        The strings are NOT re-sanitized here. receive_visit cleans them once, on
        ingest, before they are ever stored; cleaning again on every read would
        be a second implementation of the same rule, free to drift from the first.
        """
        if not self._queue_ok() or len(self.pending_from) == 0:
            return "", ""
        name = str(self.pending_name[0])
        if not name:
            return "", ""
        quote = str(self.pending_quote[0])
        if not quote:
            return f"another pet, {name}, came by to see you;", name
        return f'another pet, {name}, came by and said: "{quote}";', name

    # ---- character drift ----

    def _levels(self) -> list:
        """Trait counters as a plain list, padded if TRAITS grew since deployment.

        A contract deployed before a trait was added has a shorter array and no
        way to grow it — storage is fixed at construction. Padding here keeps such
        a pet readable instead of throwing on every action.
        """
        stored = [int(v) for v in self.trait_levels]
        while len(stored) < len(TRAITS):
            stored.append(0)
        return stored[: len(TRAITS)]

    def _character(self) -> str:
        return _character_phrase(self._levels())

    def _evolve(self, trait) -> str:
        """Let one experience move the character. Returns the trait moved, or "".

        Everything that can say no says no here, in deterministic code:

        * the owner may have switched drift off;
        * the word must be one of TRAITS — an invented one is ignored, never
          stored, and certainly never rendered into a prompt;
        * a trait stops at TRAIT_MAX, so a pet cannot become infinitely gloomy;
        * and only one nudge per EVOLVE_COOLDOWN_H virtual hours, so a character
          is something a pet grows into rather than something an owner can buy in
          an afternoon of clicking.

        THE PENDULUM. Past those guards a nudge does one of two things, never
        both. If the requested trait's OPPOSITE is standing (level > 0), the nudge
        is spent lowering that opposite by one and the requested trait does not
        grow this time: a playful pet asked to be gloomy first stops being playful.
        Only against a settled opposite does the trait itself rise. That is what
        lets a character change its mind instead of accumulating every mood it has
        ever been.

        TRAIT_MAX is therefore tested INSIDE the increment branch only, so a
        ceiling can never be a dead end. Note what that does and does not buy: the
        pendulum's own invariant is that a pair never both stand, so the case the
        placement guards against — the requested trait at TRAIT_MAX while its
        opposite is above zero — cannot be reached by any sequence of nudges, and
        moving the check back above the pendulum leaves the whole suite green
        (measured). It stays here because it is free and because the reachable
        half is real: a pet at five gloomy still refuses to grow gloomier, and a
        playful nudge still swings it back down.

        Either way the nudge is spent: the cooldown is stamped and `evolutions`
        counts up, because "it worked through some of its gloom" is as much a
        change as a new trait and must cost the same wait.
        """
        if not self.evolving:
            return ""
        if not isinstance(trait, str) or trait not in TRAITS:
            return ""
        last = int(self.last_evolved_ts)
        if last != 0 and self._elapsed(last) // 3600 < EVOLVE_COOLDOWN_H:
            return ""

        index = TRAITS.index(trait)
        opp = _opposite(trait)
        oi = TRAITS.index(opp) if opp in TRAITS else -1
        levels = self._levels()
        # _levels() pads a short array for READING; writing to a slot that is not
        # there would throw, and the pendulum touches two slots, so both have to
        # exist before either is moved.
        stored = len(self.trait_levels)
        if index >= stored or oi >= stored:
            return ""                      # storage predates one of these traits
        if oi >= 0 and levels[oi] > 0:
            self.trait_levels[oi] = u256(levels[oi] - 1)
            direction = "down"
        else:
            if levels[index] >= TRAIT_MAX:
                return ""
            self.trait_levels[index] = u256(levels[index] + 1)
            direction = "up"
        self.last_evolved_ts = u256(_now())
        self.evolutions = u256(int(self.evolutions) + 1)
        # Re-read through _levels() rather than subscripting storage: on the
        # "down" branch nothing was written at `index`, and a padded read is the
        # only form that is correct for both branches and for a short array.
        moved = self._levels()
        PetEvolved(
            # the REQUESTED word is the indexed topic in both directions, so a
            # client filtering on "gloomy" sees every nudge towards gloom —
            # including the ones that only burned playfulness down
            trait,
            level=moved[index],
            lowered=opp if direction == "down" else "",
            lowered_level=moved[oi] if direction == "down" else 0,
            direction=direction,
            character=self._character(),
            evolutions=int(self.evolutions),
        ).emit()
        return trait

    def _only_owner(self) -> None:
        if gl.message.sender_address != self.owner:
            raise gl.vm.UserError("only owner can do this")

    # ---- non-det: LLM line via leader + validator ----
    def _speak(self, prompt: str) -> dict:
        """Generate a line. No storage access inside the block — only `prompt`.

        WHY `run_nondet_unsafe` AND NOT AN `eq_principle`. This is the one
        non-deterministic call in the contract whose output is *meant* to differ
        between validators: two models writing a sentence in character will never
        agree on it, so `strict_eq` would fail every round, and
        `prompt_comparative` would be asking an LLM whether two cat noises mean
        the same thing — a judgement with no stable answer, paid for on every
        action.

        So the shape is the contract, and the text is flavour. The validator
        accepts any structurally valid reply and the deterministic code that
        follows takes only bounded values out of it: `mood_delta` is clamped to
        ±3 (`_apply_reply`), `trait` must be a member of TRAITS (`_evolve`), and
        `quote` is truncated and only ever displayed. A leader that returns
        nonsense costs a rotation, never a corrupt state.
        """
        def leader():
            return gl.nondet.exec_prompt(prompt, response_format="json")

        def validator(res) -> bool:
            if not isinstance(res, gl.vm.Return):
                return False
            return _valid_reply(res.calldata)

        out = gl.vm.run_nondet_unsafe(leader, validator)
        # in case the runtime hands back a Return wrapper instead of the payload
        if isinstance(out, gl.vm.Return):
            out = out.calldata
        return out

    def _finish(self, action: str, reply: dict, answered_guest: bool = True) -> str:
        """Close out an action: apply the reply, clear the guest, announce it.

        Every write method ends here, which is what keeps the event and the state
        it reports from drifting apart.

        `answered_guest=False` is for the one action that speaks without speaking
        to whoever is waiting at home — see visit().
        """
        quote = self._apply_reply(reply)
        # The same reply that produced the line may also have moved the character.
        # _evolve decides whether it is allowed to — see there for every way it
        # can say no.
        moved = self._evolve(reply.get("trait", ""))
        # NB: the decay clock is deliberately NOT stamped here. It is a cursor
        # over billed time, owned by _decay() alone — see there.
        # Whatever the pet just said, it said it knowing a guest had been by —
        # every action feeds _greeting() into the prompt. The greeting has
        # now been answered, so it must not colour the next line as well.
        if answered_guest:
            self._clear_greeting()
        PetSpoke(
            action,
            gl.message.sender_address,
            quote=quote,
            satiety=int(self.satiety),
            mood=int(self.mood),
            health=int(self.health),
            stage=_stage(self._age_days()),
            age_days=self._age_days(),
            character=self._character(),
            grew=moved,
        ).emit()
        return quote

    def _clear_greeting(self) -> None:
        """Drop the guest just answered. One speak, one pop — see _finish.

        A no-op on an empty queue, deliberately: _finish calls this after every
        line the pet speaks at home, and speaking with nobody waiting is the
        normal case, not an error. `del`, not `pop(0)` — GenVM's DynArray.pop()
        takes no index and would drop the NEWEST guest.
        """
        if self._queue_ok() and len(self.pending_from) > 0:
            del self.pending_from[0]
            del self.pending_name[0]
            del self.pending_quote[0]

    def _apply_reply(self, reply: dict) -> str:
        """Apply the LLM result to mood and record the line (deterministic)."""
        delta = int(reply["mood_delta"])
        if delta < -3:
            delta = -3
        elif delta > 3:
            delta = 3
        self.mood = _clamp(int(self.mood) + delta)
        quote = str(reply["quote"])[:280]
        self._record(quote)
        return quote

    def _apply_world(self, world: dict) -> None:
        """Real weather's effect on wellbeing, plus the stamp the hangover runs on.

        The one-shot numbers are exactly what they always were — this is the
        shock of looking outside, and it is charged once, to whoever paid for the
        look. What is new is the second half: the reading is kept, and _decay
        spends it an hour at a time until WORLD_STALE_H (see there).

        The stamp is written even when the reading came back "unknown", and that
        matters more than it looks. A failed check() that left the previous
        reading in place would keep last week's downpour alive indefinitely, so
        the cheapest way to keep a bad hangover running would be to make sure
        every later check() failed. Writing "unknown" ends the hangover instead.
        """
        cond = str(world.get("condition", "unknown"))
        if cond in WET_CONDITIONS:
            self.mood = _clamp(int(self.mood) - 3)
        elif cond == "clear":
            self.mood = _clamp(int(self.mood) + 3)
        temp = str(world.get("temp", "unknown"))
        # Cold is one-shot and stays one-shot: it is the only reading that costs
        # HEALTH, and health is the meter that barely heals. An hourly cold chip
        # would make a winter city a death sentence rather than a hard place.
        if temp == "freezing":
            self.health = _clamp(int(self.health) - 1)
        # the crypto market is this pet's other weather
        market = str(world.get("market", "unknown"))
        self.mood = _clamp(int(self.mood) + MARKET_MOOD.get(market, 0))
        self.last_market = market
        self.last_condition = cond
        self.last_temp = temp
        self.last_world_ts = u256(_now())

    # ===================== write methods ====================================

    @gl.public.write
    def check(self) -> str:
        """Main method: reads the real world (web), recomputes drift, speaks a line."""
        idle_h, still_alive = self._tick()
        if not still_alive:
            return str(self.last_quote)

        # --- non-det #1: read the weather (coarsened fields -> stable consensus) ---
        city = str(self.city)
        # Yesterday and the day before — never today: a past date is settled, so
        # the endpoint returns the same number to everyone. See _read_market.
        day, prev_day = _utc_day(-1), _utc_day(-2)

        def read():
            return _read_world(city, day, prev_day)

        world = json.loads(gl.eq_principle.strict_eq(read))

        # deterministically apply the weather
        self._apply_world(world)

        # --- non-det #2: a line in character ---
        snap = self._snapshot(idle_h)
        foreign, guest = self._greeting()
        prompt = _build_prompt(
            snap, world, "you look around and check the world", foreign, guest,
            "check",
        )
        reply = self._speak(prompt)

        return self._finish("check", reply)

    @gl.public.write.payable
    def feed(self) -> str:
        """Feed the pet (payable). Satiety grows proportionally to the GEN sent."""
        if not self.allow_public_feed and gl.message.sender_address != self.owner:
            raise gl.vm.UserError("feeding is owner-only for this pet")

        idle_h, still_alive = self._tick()
        if not still_alive:
            # The drift this very call applied is what killed it. The free actions
            # return the death line here and let the client show it; this one is
            # payable, and returning would keep the sender's GEN while crediting
            # nobody — not the leaderboard, not total_fed, not the pet, which is
            # dead. Raising reverts, so the money goes home. That is exactly what
            # __receive__ does in the identical situation, which is what _nourish
            # promises: those two paths never disagree about incoming value.
            raise gl.vm.UserError("pet just starved — call revive() to bring it back")

        gain = self._nourish(gl.message.sender_address, int(gl.message.value))

        snap = self._snapshot(idle_h)
        situation = (
            "you were just fed a tasty meal" if gain > 0
            else "you got petted but no food was given"
        )
        foreign, guest = self._greeting()
        prompt = _build_prompt(snap, None, situation, foreign, guest, "feed")
        reply = self._speak(prompt)

        return self._finish("feed", reply)

    @gl.public.write
    def play(self) -> str:
        """Play: mood goes up, satiety goes down.

        No cooldown and no ceiling beyond _clamp's 100 — play is deliberately the
        one mechanical route above PET_MOOD_CAP, and PLAY_SATIETY is the price of
        that route. The owner pays for mood in food.

        An egg cannot play, and the guard sits below the death check on purpose.
        A pet abandoned past its death clock is already a kitten by age, so the
        order only matters for the reading: what an owner gets back from a
        neglected pet must be the death line, never a chirpy "too young". The
        guard is also below _tick, so an egg's play() reverts the whole
        transaction — the idle time it just billed goes back with it and nobody
        is charged decay for an action the contract refused.

        An elder plays at PLAY_MOOD_ELDER: the romp is the same, the pet has
        less of it in them.
        """
        idle_h, still_alive = self._tick()
        if not still_alive:
            return str(self.last_quote)
        stage = _stage(self._age_days())
        if _stage_rank(stage) < _stage_rank(STAGE_MIN_PLAY):
            raise gl.vm.UserError("too young to play — wait until you hatch")
        self.mood = _clamp(
            int(self.mood) + (PLAY_MOOD_ELDER if stage == "elder" else PLAY_MOOD)
        )
        self.satiety = _clamp(int(self.satiety) - PLAY_SATIETY)

        snap = self._snapshot(idle_h)
        foreign, guest = self._greeting()
        prompt = _build_prompt(
            snap, None, "you just had a fun play session", foreign, guest, "play"
        )
        reply = self._speak(prompt)

        return self._finish("play", reply)

    @gl.public.write
    def pet(self) -> str:
        """Pet it: comfort, with a mechanical cap of PET_MOOD_CAP.

        The bump stops at the cap, so petting cannot be farmed into a happy pet:
        play() is the only mechanical way past it and it charges food for the
        trip. At or above the cap the mechanic is silent but the pet still
        speaks — the button is never a no-op for the player, it just stops being
        a lever.

        The cap lands HERE, before _snapshot and _speak, so the model is shown
        the mood it will actually be reacting to. It is deliberately not
        re-applied afterwards: _apply_reply adds the model's -3..+3 on top with
        no ceiling, so a petted pet may legitimately end above PET_MOOD_CAP.
        Clamping again after the reply would make the leader and a validator
        disagree about whether pet() worked.
        """
        idle_h, still_alive = self._tick()
        if not still_alive:
            return str(self.last_quote)
        mood = int(self.mood)
        if mood < PET_MOOD_CAP:
            room = PET_MOOD_CAP - mood
            self.mood = _clamp(mood + (PET_MOOD if PET_MOOD < room else room))

        snap = self._snapshot(idle_h)
        foreign, guest = self._greeting()
        prompt = _build_prompt(
            snap, None, "you are being gently petted on the head", foreign, guest,
            "pet",
        )
        reply = self._speak(prompt)

        return self._finish("pet", reply)

    @gl.public.write
    def visit(self, other: str) -> str:
        """Take the pet to see another AiPet at `other`.

        Three separate mechanisms, in this order, and the order is the point:

        1. a *view* call reads the host's on-chain state — synchronous, ordinary,
           deterministic code, because every validator reads the same chain;
        2. the LLM writes a line addressed to that host, with the host's own
           details fenced as untrusted data (see _sanitize);
        3. a *message* delivers that line to the host's `receive_visit`.

        Step 3 is asynchronous — the host does not change inside this transaction
        and there is no return value to wait for. `on='accepted'` rather than the
        default `'finalized'` because no value moves: a greeting is worth landing
        in seconds instead of after finalization (~30 min on Bradbury), and the
        worst case if this transaction were later overturned is a stray hello.

        Visiting a dead pet is allowed and simply goes unanswered: its own
        `receive_visit` turns the message away. Refusing here instead would be
        pretending we know — the host's aliveness is read from finalized state and
        may be half an hour out of date either way. The pet is told, and speaks
        accordingly.
        """
        self._only_owner()
        try:
            host_addr = Address(other)
        except Exception:
            raise gl.vm.UserError("not a valid address")
        if host_addr == self.address:
            raise gl.vm.UserError("a pet cannot visit itself")

        idle_h, still_alive = self._tick()
        if not still_alive:
            return str(self.last_quote)
        # Below the death check for the same reason as play(), and ABOVE the
        # cross-contract read below it: refusing before that read means a pet too
        # young to travel never spends gas calling a stranger, and never tells a
        # neighbour it was thinking about them.
        if _stage_rank(_stage(self._age_days())) < _stage_rank(STAGE_MIN_VISIT):
            raise gl.vm.UserError("too young to visit — wait until kitten")

        host = _neighbour_state(host_addr)          # also the authentication
        host_name = _sanitize(str(host.get("name", "")), FOREIGN_NAME_MAX) or "a stranger"
        host_stage = _sanitize(str(host.get("stage", "unknown")), FOREIGN_NAME_MAX)
        host_alive = bool(host.get("alive", True))

        counted = self._count_meeting(host_addr)
        if counted:
            self.mood = _clamp(int(self.mood) + VISIT_MOOD_GUEST)
        self.satiety = _clamp(int(self.satiety) - VISIT_SATIETY_COST)
        self.visits_sent = u256(int(self.visits_sent) + 1)

        snap = self._snapshot(idle_h)
        foreign = (
            f"you are visiting another pet called {host_name} "
            f"(life stage: {host_stage}), who is currently "
            f"{'awake' if host_alive else 'not alive'};"
        )
        # A guest waiting at home is NOT answered here — the pet is out, greeting
        # somebody else — so it is neither put in this prompt nor consumed by it.
        # It stays pending and gets its answer the next time the pet speaks at
        # home, which is the only reading under which the friend is not simply
        # forgotten because their host happened to go out.
        prompt = _build_prompt(
            snap, None,
            f"you walked over to say hello to {host_name} — greet them in your own voice",
            foreign,
            action="visit",
        )
        reply = self._speak(prompt)
        quote = self._finish("visit", reply, answered_guest=False)

        # The greeting itself. Anything after this line still runs — the message
        # is queued by consensus, not executed here.
        gl.get_contract_at(host_addr).emit(on="accepted").receive_visit(quote)
        PetVisited(
            host_addr,
            quote=quote,
            host_name=host_name,
            meetings=int(self.friends.get(host_addr) or 0),
            counted=counted,
        ).emit()
        return quote

    @gl.public.write
    def receive_visit(self, quote: str) -> None:
        """Another pet says hello. Called by ITS contract, never by a wallet.

        Deliberately does NOT call the LLM: this runs inside a message on gas the
        sender chose, and an LLM call here could bounce the whole delivery — the
        same reasoning as `__receive__`. The pet answers the next time it speaks,
        because every action feeds `_greeting()` into its prompt.

        Deliberately does NOT stamp `last_interaction_ts` either. Company is not
        food: if being greeted reset the decay clock, two pets could keep each
        other alive forever without anyone ever paying to feed them. Skipping the
        stamp also means skipping `_tick()` — one charges idle time and the other
        clears it, and calling only the first would bill that same idle period
        twice on the next action.
        
        There is deliberately no age guard here either. An egg is too young to
        walk to a neighbour, but old enough to be called on — visiting is the one
        thing a pet can do FOR another pet, and locking it out of receiving would
        leave the youngest pets, the ones with nothing else to do, alone.
        """
        guest = gl.message.sender_address
        if guest == self.address:
            raise gl.vm.UserError("a pet cannot greet itself")
        if not self.alive:
            raise gl.vm.UserError("this pet is not alive to receive guests")

        state = _neighbour_state(guest)             # proves the caller is a pet
        name = _sanitize(str(state.get("name", "")), FOREIGN_NAME_MAX) or "a stranger"
        line = _sanitize(quote, GREETING_MAX)

        counted = self._count_meeting(guest)
        if counted:
            self.mood = _clamp(int(self.mood) + VISIT_MOOD_HOST)
        self.visits_received = u256(int(self.visits_received) + 1)

        # Room in the prompt is rationed; friendship is not. A guest who arrives
        # to a full queue keeps the mood payout, the friends counter and the
        # history line above — they just do not get a line in the next prompt.
        # The oldest is never evicted: whoever knocked first is answered first.
        queued = self._queue_ok() and len(self.pending_from) < GREETING_QUEUE_MAX
        if queued:
            self.pending_from.append(guest)
            self.pending_name.append(name)
            self.pending_quote.append(line)
        # _note, not _record: this is the guest talking, not the pet.
        self._note(f'{name} came by: "{line}"' if line else f"{name} came by.")

        PetGreeted(
            guest,
            guest_name=name,
            quote=line,
            counted=counted,
            meetings=int(self.friends.get(guest) or 0),
            mood=int(self.mood),
            queued=queued,
            queue_len=len(self.pending_from),
        ).emit()

    @gl.public.write.payable
    def revive(self) -> str:
        """Bring a dead pet back. Anyone may pay, and payment counts as feeding.

        Two roads, and no third: send at least REVIVE_COST, or send nothing at
        all and let the till pay — which it does only when the community has fed
        this pet REVIVE_COST of NEW food since the last time the till covered a
        death (see _till_revive_ready). A till-revive LOCKS that GEN rather than
        paying it to whoever called: rewarding the reviver would turn a
        well-fed community pet into a faucet a stranger drains by grief-reviving
        it, and the point of the reserve is that dying still costs somebody.
        """
        if self.alive:
            raise gl.vm.UserError("pet is already alive")

        # Two ways back: pay for it, or let the till pay. Nothing in between —
        # a part payment is not topped up out of the reserve, because a reserve
        # that can be drained a slice at a time is not a reserve.
        value = int(gl.message.value)
        from_till = value == 0
        if 0 < value < REVIVE_COST:
            raise gl.vm.UserError(
                "revive costs at least 1 GEN (send it, or leave it in the till)"
            )
        if from_till and not self._till_revive_ready():
            raise gl.vm.UserError(
                "revive costs at least 1 GEN (send it, or leave it in the till)"
            )

        self.alive = True
        self.died_ts = u256(0)
        self.revives = u256(int(self.revives) + 1)
        # comes back weakened, not brand new — dying has a cost
        self.health = u256(REVIVE_HEALTH)
        self.satiety = u256(REVIVE_SATIETY)
        self.mood = u256(REVIVE_MOOD)
        # a new life banks its own well-fed hours; the corpse's do not carry over
        self.health_regen_acc = u256(0)
        if from_till:
            # The death tax, paid by the community that fed it. The GEN does not
            # move and does not come back: burned_wei is subtracted from every
            # figure this contract reports from here on. Nobody is credited for
            # it either — you cannot climb the leaderboard by spending money
            # that was already in the box, and a stranger who calls this is
            # spending the community's GEN, not pocketing it.
            self.burned_wei = u256(int(self.burned_wei) + REVIVE_COST)
            # Immediately, not at finalization: this is what stops the next
            # death being free. See _till_revive_ready. total_fed does NOT grow.
            self.till_revive_at_fed = u256(int(self.total_fed))
        else:
            # The paid path, unchanged. This is new food, so it grows total_fed
            # and credits the payer — and deliberately does NOT move
            # till_revive_at_fed, because that payment is exactly what should
            # let a LATER death be covered by the till.
            self.total_fed = u256(int(self.total_fed) + value)
            self._credit_feeder(gl.message.sender_address, value)
        # restart the decay clock so the revive isn't instantly undone
        self.last_interaction_ts = u256(_now())
        PetRevived(
            gl.message.sender_address,
            paid_wei=str(value),
            from_till=from_till,
            burned_wei=str(REVIVE_COST if from_till else 0),
            revives=int(self.revives),
        ).emit()

        snap = self._snapshot(0)
        foreign, guest = self._greeting()
        prompt = _build_prompt(
            snap, None, "you were just brought back to life after dying", foreign, guest
        )
        reply = self._speak(prompt)

        return self._finish("revive", reply)

    @gl.public.write.payable
    def __receive__(self) -> None:
        """Accept a plain GEN transfer — money sent to the pet feeds the pet.

        Without this handler a bare transfer just sat in the balance, credited to
        nobody: the leaderboard understated, `total_fed` understated, and only the
        owner could ever get it out. Now it is booked exactly like `feed()`; the
        only difference is that a transfer buys no line, because this runs on
        whatever gas the sender supplied and an LLM call here could bounce it.

        Refusing is deliberate where it happens. A raise rolls the whole delivery
        back and the sender is refunded (`__on_errored_message__`), which beats
        swallowing money the pet cannot use.
        """
        who = gl.message.sender_address
        if not self.allow_public_feed and who != self.owner:
            raise gl.vm.UserError("feeding is owner-only for this pet")

        # _tick() raises if the pet is already dead, and may kill it right here.
        idle_h, still_alive = self._tick()
        if not still_alive:
            raise gl.vm.UserError("pet just starved — call revive() to bring it back")

        value = int(gl.message.value)
        if value > 0:
            self._nourish(who, value)

    @gl.public.write
    def withdraw(self, amount_wei: int) -> None:
        """Send accumulated food money from the contract to the owner.

        The payout settles when this transaction finalizes, not when it is
        accepted. See _Payee for why it goes through the EVM proxy.
        """
        self._only_owner()
        amount = int(amount_wei)
        if amount <= 0:
            raise gl.vm.UserError("amount must be positive")
        # Two guards, in this order. The first is about money that is not there
        # at all; the second is about money that is there and is spoken for.
        # Swapping them would tell an owner asking for ten times the balance
        # about the reserve, which is true but not the answer to the question.
        if amount > int(self.balance):
            raise gl.vm.UserError("insufficient contract balance")
        if amount > self._withdrawable():
            raise gl.vm.UserError("revive reserve — leave at least 1 GEN in the till")
        _Payee(self.owner).emit_transfer(value=u256(amount))
        OwnerWithdrew(
            self.owner,
            amount_wei=str(amount),
            # what is left once the transfer settles — the balance has not moved
            # yet, and anything the till already burned was never theirs to take
            remaining_wei=str(self._effective_balance() - amount),
        ).emit()

