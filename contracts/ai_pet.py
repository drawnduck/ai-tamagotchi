    @gl.public.write
    def visit(self, other: str) -> str:
        """Take the pet to see another AiPet at `other`.

        Three separate mechanisms, in this order, and the order is the point:

        1. a *view* call reads the host's on-chain state — synchronous, ordinary,
           deterministic code, because every validator reads the same chain;
        2. the LLM writes a line addressed to that host, with the host's own
           details fenced as untrusted data (see _sanitize);
        3. a *message* delivers that line to the host's `receive_visit`.

        Step 3 is asynchronous — the host does not change inside this transaction
        and there is no return value to wait for. `on='accepted'` rather than the
        default `'finalized'` because no value moves: a greeting is worth landing
        in seconds instead of after finalization (~30 min on Bradbury), and the
        worst case if this transaction were later overturned is a stray hello.

        Visiting a dead pet is allowed and simply goes unanswered: its own
        `receive_visit` turns the message away. Refusing here instead would be
        pretending we know — the host's aliveness is read from finalized state and
        may be half an hour out of date either way. The pet is told, and speaks
        accordingly.
        """
        self._only_owner()
        try:
            host_addr = Address(other)
        except Exception:
            raise gl.vm.UserError("not a valid address")
        if host_addr == self.address:
            raise gl.vm.UserError("a pet cannot visit itself")

        idle_h, still_alive = self._tick()
        if not still_alive:
            return str(self.last_quote)

        host = _neighbour_state(host_addr)          # also the authentication
        host_name = _sanitize(str(host.get("name", "")), FOREIGN_NAME_MAX) or "a stranger"
        host_stage = _sanitize(str(host.get("stage", "unknown")), FOREIGN_NAME_MAX)
        host_alive = bool(host.get("alive", True))

        counted = self._count_meeting(host_addr)
        if counted:
            self.mood = _clamp(int(self.mood) + VISIT_MOOD_GUEST)
        self.satiety = _clamp(int(self.satiety) - VISIT_SATIETY_COST)
        self.visits_sent = u256(int(self.visits_sent) + 1)

        snap = self._snapshot(idle_h)
        foreign = (
            f"you are visiting another pet called {host_name} "
            f"(life stage: {host_stage}), who is currently "
            f"{'awake' if host_alive else 'not alive'};"
        )
        # A guest waiting at home is NOT answered here — the pet is out, greeting
        # somebody else — so it is neither put in this prompt nor consumed by it.
        # It stays pending and gets its answer the next time the pet speaks at
        # home, which is the only reading under which the friend is not simply
        # forgotten because their host happened to go out.
        prompt = _build_prompt(
            snap, None,
            f"you walked over to say hello to {host_name} — greet them in your own voice",
            foreign,
        )
        reply = self._speak(prompt)
        quote = self._finish("visit", reply, answered_guest=False)

        # The greeting itself. Anything after this line still runs — the message
        # is queued by consensus, not executed here.
        gl.get_contract_at(host_addr).emit(on="accepted").receive_visit(quote)
        PetVisited(
            host_addr,
            quote=quote,
            host_name=host_name,
            meetings=int(self.friends.get(host_addr) or 0),
            counted=counted,
        ).emit()
        return quote

    @gl.public.write
    def receive_visit(self, quote: str) -> None:
        """Another pet says hello. Called by ITS contract, never by a wallet.

        Deliberately does NOT call the LLM: this runs inside a message on gas the
        sender chose, and an LLM call here could bounce the whole delivery — the
        same reasoning as `__receive__`. The pet answers the next time it speaks,
        because every action feeds `_greeting()` into its prompt.

        Deliberately does NOT stamp `last_interaction_ts` either. Company is not
        food: if being greeted reset the decay clock, two pets could keep each
        other alive forever without anyone ever paying to feed them. Skipping the
        stamp also means skipping `_tick()` — one charges idle time and the other
        clears it, and calling only the first would bill that same idle period
        twice on the next action.
        """
        guest = gl.message.sender_address
        if guest == self.address:
            raise gl.vm.UserError("a pet cannot greet itself")
        if not self.alive:
            raise gl.vm.UserError("this pet is not alive to receive guests")

        state = _neighbour_state(guest)             # proves the caller is a pet
        name = _sanitize(str(state.get("name", "")), FOREIGN_NAME_MAX) or "a stranger"
        line = _sanitize(quote, GREETING_MAX)

        counted = self._count_meeting(guest)
        if counted:
            self.mood = _clamp(int(self.mood) + VISIT_MOOD_HOST)
        self.visits_received = u256(int(self.visits_received) + 1)

        self.pending_from = guest
        self.pending_name = name
        self.pending_quote = line
        # _note, not _record: this is the guest talking, not the pet.
        self._note(f'{name} came by: "{line}"' if line else f"{name} came by.")

        PetGreeted(
            guest,
            guest_name=name,
            quote=line,
            counted=counted,
            meetings=int(self.friends.get(guest) or 0),
            mood=int(self.mood),
        ).emit()

    @gl.public.write.payable
    def revive(self) -> str:
        """Bring a dead pet back for REVIVE_COST. Anyone may pay — it counts as feeding."""
        if self.alive:
            raise gl.vm.UserError("pet is already alive")

        value = int(gl.message.value)
        if value < REVIVE_COST:
            raise gl.vm.UserError("revive costs at least 1 GEN")

        self.alive = True
        self.died_ts = u256(0)
        self.revives = u256(int(self.revives) + 1)
        # comes back weakened, not brand new — dying has a cost
        self.health = u256(REVIVE_HEALTH)
        self.satiety = u256(REVIVE_SATIETY)
        self.mood = u256(REVIVE_MOOD)
        # a new life banks its own well-fed hours; the corpse's do not carry over
        self.health_regen_acc = u256(0)
        self.total_fed = u256(int(self.total_fed) + value)
        self._credit_feeder(gl.message.sender_address, value)
        # restart the decay clock so the revive isn't instantly undone
        self.last_interaction_ts = u256(_now())
        PetRevived(
            gl.message.sender_address,
            paid_wei=str(value),
            revives=int(self.revives),
        ).emit()

        snap = self._snapshot(0)
        foreign, guest = self._greeting()
        prompt = _build_prompt(
            snap, None, "you were just brought back to life after dying", foreign, guest
        )
        reply = self._speak(prompt)

        return self._finish("revive", reply)

    @gl.public.write.payable
    def __receive__(self) -> None:
        """Accept a plain GEN transfer — money sent to the pet feeds the pet.

        Without this handler a bare transfer just sat in the balance, credited to
        nobody: the leaderboard understated, `total_fed` understated, and only the
        owner could ever get it out. Now it is booked exactly like `feed()`; the
        only difference is that a transfer buys no line, because this runs on
        whatever gas the sender supplied and an LLM call here could bounce it.

        Refusing is deliberate where it happens. A raise rolls the whole delivery
        back and the sender is refunded (`__on_errored_message__`), which beats
        swallowing money the pet cannot use.
        """
        who = gl.message.sender_address
        if not self.allow_public_feed and who != self.owner:
            raise gl.vm.UserError("feeding is owner-only for this pet")

        # _tick() raises if the pet is already dead, and may kill it right here.
        idle_h, still_alive = self._tick()
        if not still_alive:
            raise gl.vm.UserError("pet just starved — call revive() to bring it back")

        value = int(gl.message.value)
        if value > 0:
            self._nourish(who, value)

    @gl.public.write
    def withdraw(self, amount_wei: int) -> None:
        """Send accumulated food money from the contract to the owner.

        The payout settles when this transaction finalizes, not when it is
        accepted. See _Payee for why it goes through the EVM proxy.
        """
        self._only_owner()
        amount = int(amount_wei)
        if amount <= 0:
            raise gl.vm.UserError("amount must be positive")
        if amount > int(self.balance):
            raise gl.vm.UserError("insufficient contract balance")
        _Payee(self.owner).emit_transfer(value=u256(amount))
        OwnerWithdrew(
            self.owner,
            amount_wei=str(amount),
            # what is left once the transfer settles — the balance has not moved yet
            remaining_wei=str(int(self.balance) - amount),
        ).emit()

