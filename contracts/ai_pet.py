    @gl.public.view
    def get_top_feeders(self, limit: int) -> list:
        """Community leaderboard, biggest contributor first.

        `limit` caps the rows returned; pass 0 (or less) for the whole board. The
        cap matters — a popular community pet accumulates feeders without bound,
        and trimming here beats shipping the whole map to every caller.

        Amounts are returned as strings — wei exceeds JS Number.MAX_SAFE_INTEGER.
        """
        rows = [
            {"address": addr.as_hex, "wei": str(int(amount))}
            for addr, amount in self.feeders.items()
        ]
        rows.sort(key=lambda r: int(r["wei"]), reverse=True)
        n = int(limit)
        return rows if n <= 0 else rows[:n]

