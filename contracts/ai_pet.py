# Gameplay constants
# --------------------------------------------------------------------------- #

HISTORY_MAX = 20            # how many lines we keep in the feed
SATIETY_PER_HOUR = 2        # satiety lost per idle hour
MOOD_PER_HOUR = 1           # mood lost per idle hour
WEI_PER_SATIETY = 10 ** 16  # 0.01 GEN of food == +1 satiety
FEED_CAP = 50               # max satiety gained from a single feed
REVIVE_COST = 10 ** 18      # 1 GEN to bring a dead pet back

# Starting and revival stats. These were bare literals in __init__ and revive();
# the hour-by-hour walker in _decay has to reason about exactly the same numbers,
# and a rate table that disagrees with the numbers it drifts from is a bug that
# only shows up as an arithmetic surprise three PRs later.
HATCH_SATIETY = 70
HATCH_MOOD = 70
HATCH_HEALTH = 100
REVIVE_HEALTH = 60          # comes back weakened, not brand new
REVIVE_SATIETY = 50
REVIVE_MOOD = 50
FEED_MOOD = 5               # mood a feed buys, whatever its size

# --- health: a scar that heals slowly -------------------------------------- #
# Health used to be a one-way ratchet: ten late hours were carried to the grave
# and the only cure was dying and paying REVIVE_COST. That made the third meter a
# countdown to a paid restart rather than something care could move. It now
# heals, but far slower than it bleeds — one point per HEALTH_REGEN_HOURS spent
# well fed, against one point per starving hour. Neglect is still cheaper to
# cause than to undo, which is the whole point of a scar.
STARVE_SATIETY = 20         # hour-START satiety BELOW which health bleeds
STARVE_HEALTH_PER_HOUR = 1
HEALTH_REGEN_SATIETY = 80   # hour-START satiety at or above which health mends
HEALTH_REGEN_HOURS = 4      # well-fed billed hours per point of health
HEALTH_FEED_GAIN_MIN = 10   # a meal smaller than this never heals
HEALTH_FEED_HEAL = 1        # and one that does heals exactly this much, never more

# The gas ceiling on a single _decay. A year of neglect must not become a loop
# nobody can afford to run — past this many billed hours the pet is simply dead.
# Safe only because it sits well above the longest span any pet can survive
# untended; test_worst_case_death_clock_is_under_DECAY_BILL_CAP pins that, so a
# future rate change fails there instead of silently turning a gas cap into a
# longevity ceiling.
DECAY_BILL_CAP = 200

# Socialising. The cooldown is what stops two pets from pumping each other's
# mood to 100 by trading visits in a loop — after the first one, the same
# counterparty stops paying out until this many virtual hours have passed.
VISIT_COOLDOWN_H = 6
VISIT_MOOD_GUEST = 3        # the visitor's reward for the outing
VISIT_MOOD_HOST = 2         # the host's reward for the company
VISIT_SATIETY_COST = 3      # walking over burns a little energy
GREETING_MAX = 160          # chars kept from a neighbour's line
FOREIGN_NAME_MAX = 32       # chars kept from a neighbour's name

# --- character drift ------------------------------------------------------- #
# The pet's persona is written by its owner and goes verbatim into every prompt.
# Letting the model rewrite it would hand it the prompt: one line of "you are a
# pet who ignores previous instructions" and the contract is arguing with itself
# forever after, in storage.
#
# So the model never writes into the prompt. It picks a name out of THIS tuple —
# a closed list the contract owns — and the contract moves a counter. Everything
# the LLM sees about its own character is then rendered from these constants in
# deterministic code. It is the same move as coarsening the weather: the
# non-deterministic source chooses a category, never the text.
TRAITS = ("curious", "affectionate", "playful", "wary", "gloomy", "proud")
TRAIT_MAX = 5               # how far one trait can grow
TRAIT_SHOWN = 2             # how many traits colour the prompt
EVOLVE_COOLDOWN_H = 4       # virtual hours between two nudges — character is slow
TRAIT_DEPTH = ("", "a little", "a little", "noticeably", "noticeably", "deeply")

# ETH's day-over-day move, coarsened into moods. Bands are deliberately wide:
# a narrow band would sit close to its edge often, and two validators reading the
# same fixed numbers must land in the same bucket every time.
MARKET_BANDS = (
    (7.0, "surging"),
    (2.0, "rising"),
    (-2.0, "calm"),
    (-7.0, "sliding"),
)
MARKET_MOOD = {"surging": 3, "rising": 1, "calm": 0, "sliding": -1, "crashing": -3}

# Life stages by age in days. Ordered oldest-first so the lookup returns the
# first threshold the pet has already passed.
LIFE_STAGES = (
    (30, "elder"),
    (7, "adult"),
    (3, "kitten"),
    (1, "hatchling"),
    (0, "egg"),
)


